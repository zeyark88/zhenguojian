package core

import "runtime/debug"

// 嵌入式性能优化：为本地核心设置软内存上限。
//
// 背景：本地核心（站源目录 / 搜索 / 下载解包 / 弹幕解析）运行在
// libmpv、FFmpegKit 等原生媒体库同一进程内。Go 侧默认没有内存上限，
// 大目录页与批量下载的瞬时堆增长会持续推高水位，与视频解码缓冲
// 互相挤占，在低内存设备或系统查杀积极的环境（如鸿蒙）中更容易
// 触发整应用回收。
//
// SetMemoryLimit 是软上限（GOGC 仍生效，只是 GC 目标不再无限外推）：
// 512MiB 足够容纳最大目录快照与下载元数据，同时把堆水位约束在
// 与媒体库共存的合理区间。达到上限时 GC 变得积极而不是直接崩溃。
func init() {
	debug.SetMemoryLimit(512 << 20)
}
